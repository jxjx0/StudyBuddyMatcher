package com.studybuddy.user.repository;

import com.studybuddy.user.model.Course;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.stereotype.Repository;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;
import java.util.Optional;

@Repository
public class CourseRepository {
	private static final RowMapper<Course> COURSE = (rs, row) ->
			new Course(rs.getObject("course_id", java.util.UUID.class), rs.getString("course_code"), rs.getString("course_name"));
	private final JdbcTemplate jdbc;
	public CourseRepository(JdbcTemplate jdbc) { this.jdbc = jdbc; }
	public List<Course> findAll() {
		return jdbc.query("SELECT course_id, course_code, course_name FROM courses ORDER BY course_code", COURSE);
	}
	public Optional<Course> findByCode(String courseCode) {
		return jdbc.query("SELECT course_id, course_code, course_name FROM courses WHERE course_code = ?", COURSE, courseCode)
				.stream().findFirst();
	}
	// course_id is the primary key and is generated by the database, so update by code first and insert only if it is new.
	@Transactional
	public Course save(Course course) {
		String code = course.getCourseCode().trim().toUpperCase();
		String name = course.getCourseName().trim();
		if (jdbc.update("UPDATE courses SET course_name = ? WHERE course_code = ?", name, code) == 0) {
			jdbc.update("INSERT INTO courses(course_code, course_name) VALUES (?, ?)", code, name);
		}
		return findByCode(code).orElseThrow();
	}
}
